# 句首连接词单独判断，避免误伤正文里的「最后一刻」
LEAD_CONNECTIVES = ("首先", "其次", "再次", "最后", "第一", "第二", "第三")


def lint(text: str) -> list[str]:
    """返回命中的词（去重，保持出现顺序）。"""
    if not text:
        return []
    hits: list[str] = []
    for group in GROUPS.values():
        for w in group:
            if w and w in text and w not in hits:
                hits.append(w)
    # 句首连接词：只抓「首先，」「其次、」这种
    for w in LEAD_CONNECTIVES:
        if re.search(rf"(^|[。！？\n；])\s*{w}\s*[，,、：:]", text) and w not in hits:
            hits.append(w)
    return hits


def explain(hits: list[str]) -> str:
    """把命中词归类成一句人话。"""
    if not hits:
        return ""
    parts = []
    for name, group in GROUPS.items():
        got = [w for w in hits if w in group]
        if got:
            parts.append(f"{name}：{'、'.join(got[:5])}")
    lead = [w for w in hits if w in LEAD_CONNECTIVES]
    if lead:
        parts.append(f"三段式开头：{'、'.join(lead)}")
    return "；".join(parts)
